/**
 * createLegacyCipher must stay byte-identical to the removed crypto.createCipher().
 *
 * WHY THIS MATTERS MORE THAN A NORMAL TEST: 2824 of 2851 account_funds_pass records
 * (99%) were written in the old IV-less createCipher format. verifyFundsPass() compares
 * a freshly-encrypted attempt against that stored ciphertext, so if this derivation
 * drifts by a single byte, EVERY legacy funds password silently stops verifying — and
 * the originals cannot be recovered from what is stored. There is no graceful
 * degradation here; it is correct or the data is inaccessible.
 *
 * crypto.createCipher derived key+IV from the password using OpenSSL's EVP_BytesToKey
 * (MD5, no salt, one iteration). It was REMOVED in Node 22, which is why the
 * replacement exists.
 *
 * The expected values below were generated by the GENUINE crypto.createCipher on Node
 * v20.20.2 — they are not self-produced by the implementation under test, which would
 * make this circular. The key is a throwaway, not the production one.
 */

const path = require('path');

const mockConfigFs = () => {
  const actual = jest.requireActual('fs');
  return {
    ...actual,
    readFileSync: jest.fn((filePath, options) => {
      if (path.basename(filePath) === 'config.json') {
        return actual.readFileSync(path.join(__dirname, 'test-config.json'), options);
      }
      return actual.readFileSync(filePath, options);
    }),
  };
};
jest.doMock('node:fs', mockConfigFs);
jest.doMock('fs', mockConfigFs);
jest.doMock('firebase-admin', () => ({
  initializeApp: jest.fn(),
  credential: { cert: jest.fn(() => 'mock-cert') },
  messaging: jest.fn(() => ({ sendAll: jest.fn(), sendEach: jest.fn() })),
}));

const utils = require('../utils');

// Generated on Node v20.20.2 by: crypto.createCipher('aes192', KEY)
const KEY = 'actifit-legacy-cipher-test-key';
const VECTORS = {
  '': 'b5b29331c1bb4026166dd1138c397d8a',
  'a': '3523f759088c729153bf796734377f4e',
  'password123': '70092e3d39d93ae226a2592c65151f73',
  'Str0ng!Pass#2026': '94031d3ece62fa309e8b610298d4b3adea80c97a48655e83082d5081c40694ed',
  'ünïcødé-çase': 'fad0ff68150ee3ae785db912e16fb9cad407a66d3ce00682be00cc185b7caf30',
  'xxxxxxxxxxxxxxxx': '80aabd0d8054c05275b3ecb73b03701a4a81afc9c1bead4dfc30e48201c115a1',
  'yyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyyy':
    '4a4946694abc8eb44939da2cd3fd3a3c783c1744cfa3f5fd58da6bc85f14f68e3a4e706192a4ea783be545a6ae5ad883eb0d0fd6a26005bec482c9320471d50c7721439a42a5dcd20a17eae4cb239716',
};

const encrypt = (plaintext, key = KEY, algo = 'aes192') => {
  const c = utils.createLegacyCipher(algo, key);
  return c.update(plaintext, 'utf8', 'hex') + c.final('hex');
};

describe('createLegacyCipher — byte-identical to the removed crypto.createCipher', () => {
  it('confirms the premise: the API it replaces is gone from Node 22 onward', () => {
    // Version-aware on purpose. Asserting 'undefined' unconditionally would fail for
    // anyone still running the suite on Node 20, where createCipher legitimately exists
    // and the vectors below were generated.
    const major = Number(process.version.match(/^v(\d+)/)[1]);
    expect(typeof require('crypto').createCipher).toBe(major >= 22 ? 'undefined' : 'function');
  });

  describe.each(Object.entries(VECTORS))('plaintext of length %#', (plaintext, expected) => {
    it(`reproduces the Node 20 ciphertext exactly (${plaintext.length} chars)`, () => {
      expect(encrypt(plaintext)).toBe(expected);
    });
  });

  it('is deterministic — the same input always yields the same ciphertext', () => {
    // verifyFundsPass depends on this: it re-encrypts the attempt and compares against a
    // stored value, which only works because there is no random IV.
    expect(encrypt('password123')).toBe(encrypt('password123'));
  });

  it('produces different ciphertext for a different key', () => {
    expect(encrypt('password123', 'some-other-key')).not.toBe(VECTORS['password123']);
  });

  it('accepts the aes-192-cbc spelling as well as aes192', () => {
    expect(encrypt('password123', KEY, 'aes-192-cbc')).toBe(VECTORS['password123']);
  });

  it('throws on an algorithm it cannot faithfully reproduce', () => {
    // Guessing key/IV lengths for an unmapped algorithm would produce plausible-looking
    // ciphertext that silently fails to match anything stored.
    expect(() => utils.createLegacyCipher('aes-256-cbc', KEY)).toThrow(/unsupported legacy cipher/);
    expect(() => utils.createLegacyCipher('aes128', KEY)).toThrow(/unsupported legacy cipher/);
  });
});
